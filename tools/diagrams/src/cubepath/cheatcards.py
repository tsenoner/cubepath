# ── Print-variant diagrams ────────────────────────────────────────────
# The cards re-render every diagram in `diagrams.CARD` style rather than
# post-processing the screen SVG. That is the difference between a palette
# that is chosen and gated (`palette.contrast`) and a list of hex-string
# substitutions that silently stops matching the day diagrams.py changes.


def build_print_svgs() -> dict[str, int]:
    """Re-render every diagram the cards use, in card style."""
    from cubepath.diagrams import (
        _align_edge_cases,
        _corner_case_steps,
        _corner_pos_case,
        _edge_case_steps,
        _orient_corner_case,
        _orient_corner_cases_15,
        _step_cases,
    )

    if _CARD_SVG.exists():
        shutil.rmtree(_CARD_SVG)
    counts: dict[str, int] = {}

    def bump(path: Path) -> None:
        counts[path.parent.name] = counts.get(path.parent.name, 0) + 1

    for case in all_cases():
        bump(render(case, _CARD_SVG, style=CARD))
    # Card 3 renders from the algorithm it prints, never from JPerm's primary:
    # the repo's Z-Perm and JPerm's solve states differing by a `y` rotation.
    for case in card_pll_cases():
        bump(render(case, _CARD_SVG, style=CARD))
    steps = (
        _step_cases()
        + _corner_case_steps()
        + _edge_case_steps()
        + _orient_corner_cases_15()
        + _align_edge_cases()
        + [_orient_corner_case(), _corner_pos_case()]
    )
    for step in steps:
        bump(render_step(step, _CARD_SVG, style=CARD))

    if set(counts) != {"oll", "pll", "pll-full", "steps"}:
        raise AssertionError(f"unexpected card diagram categories: {sorted(counts)}")
    return counts



"""Printable card set: imposition, build gates and the CLI.

Four ID-1 panels (85.6 x 53.98 mm) — three numbered progression cards and one
annex. What each card *says* lives in `cards.py`; this module lays them out on
paper, compiles them and refuses to ship a broken one.

Nothing here retypes an algorithm. Every 3x3 string comes from `algs.py` via
`notation.CHUNKS` or `notation.PLL_CHUNKS`; every big-cube string is read out
of the app script that pins it for CI; recognition wording is generated by
`recognition.py`. Colour is derived by exact-token lookup in `palette.FAMILY`,
never assigned by hand.

Four failure modes this module actively guards, because each one silently
ships a wrong card:

*   Typst's smart quotes rewrite every ASCII prime to U+2019, which cubing.js
    refuses to parse — `#set smartquote(enabled: false)` plus a gate.
*   Typst exits 0 on an unknown font family, so a macOS-only font compiles
    clean here and falls back to something else everywhere else — the build
    runs `--ignore-system-fonts` and treats warnings as errors.
*   Typst silently paginates on overflow, so a too-full card becomes a third
    page instead of an error — the build asserts the page count and geometry.
*   A duplex imposition that pairs the wrong front with the wrong back looks
    perfect on a proof sheet. The row-duplication theorem is asserted, not
    assumed (see `_duplex`).
"""


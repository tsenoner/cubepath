def _compile_all(jobs: list[tuple[Path, Path]]) -> None:
    """Compile independent Typst sources concurrently.

    Every sheet is a separate `typst` process over a separate source, so they
    have nothing to share and no reason to queue. The per-card gates still run
    afterwards on the finished PDFs, and `fit()` still panics inside each
    process, so nothing is traded away for the wall-clock.
    """
    with ThreadPoolExecutor(max_workers=min(8, len(jobs) or 1)) as ex:
        for _ in ex.map(lambda j: _compile(*j), jobs):
            pass


def _compile(src: Path, pdf: Path) -> None:
    """Compile with only bundled fonts, treating warnings as errors.

    Typst exits 0 on an unknown font family, so a macOS-only font would
    compile clean here and silently fall back everywhere else.
    """
    proc = subprocess.run(
        ["typst", "compile", "--ignore-system-fonts", "--root", str(_GUIDE), str(src), str(pdf)],
        capture_output=True,
    )
    if proc.returncode != 0:
        raise RuntimeError(proc.stderr.decode() or f"typst failed on {src}")
    if b"warning:" in proc.stderr:
        raise AssertionError(f"typst warnings compiling {src}:\n{proc.stderr.decode()}")


def _pdfinfo(pdf: Path) -> dict[str, str]:
    """Parse `pdfinfo`, refusing to treat a failed probe as an empty result.

    Without the return-code check a broken or unreadable PDF comes back as
    `{}`, and `gate_card` then reports "must be exactly 2 pages, got None" —
    which sends whoever reads it looking for a layout bug that is not there.
    """
    proc = subprocess.run(["pdfinfo", str(pdf)], capture_output=True, text=True)
    if proc.returncode != 0:
        raise RuntimeError(f"pdfinfo failed on {pdf}: {proc.stderr.strip()}")
    out = proc.stdout
    return dict(
        (k.strip(), v.strip())
        for k, _, v in (line.partition(":") for line in out.splitlines())
        if k
    )


def pdf_text(pdf: Path) -> str:
    return subprocess.run(["pdftotext", str(pdf), "-"], capture_output=True, text=True).stdout


@functools.cache
def _leaks() -> tuple[str, ...]:
    """Markup that must never survive into a card's rendered text.

    Derived from the preamble rather than listed: naming six of the ~37 `#let`
    helpers left every helper added afterwards uncovered by default, which is
    the opposite of what a gate is for. A leak shows up as the call itself —
    either the bracket form with its `#` eaten, or the code form printed whole.
    """
    names = sorted(set(re.findall(r"#let (\w+)", _preamble())))
    sizes = [n for n in names if n.isupper()]
    pats = {f"{n}[" for n in names}
    pats |= {f"#{n}(" for n in names} | {f"#{n}[" for n in names}
    pats |= {f"{n}({s}," for n in names for s in sizes}
    return tuple(sorted(pats))


def gate_card(card: Card, pdf: Path) -> str:
    """Assert one card is two ID-1 pages of legible, un-banned content."""
    info = _pdfinfo(pdf)
    if info.get("Pages") != "2":
        raise AssertionError(
            f"{card.slug}: must be exactly 2 pages, got {info.get('Pages')} — "
            "content overflowed and Typst paginated silently"
        )
    want_w, want_h = CARD_W * 72 / 25.4, CARD_H * 72 / 25.4
    m = re.match(r"([\d.]+) x ([\d.]+)", info.get("Page size", ""))
    if not m or abs(float(m.group(1)) - want_w) > 0.1 or abs(float(m.group(2)) - want_h) > 0.1:
        raise AssertionError(
            f"{card.slug}: page size {info.get('Page size')} != {want_w:.3f} x {want_h:.3f} pt"
        )

    text = pdf_text(pdf)
    for bad, label in (("’", "U+2019 right single quote"), ("′", "U+2032 prime")):
        if bad in text:
            raise AssertionError(
                f"{card.slug}: {label} in the PDF — smartquote is rewriting primes "
                "and cubing.js cannot parse the printed algorithms"
            )

    flat = re.sub(r"\s+", "", text)
    for leak in _leaks():
        if leak.replace(" ", "") in flat:
            raise AssertionError(f"{card.slug}: raw Typst markup {leak!r} rendered as text")

    # BANNED is insider shorthand with a plain equivalent; PLAIN is vocabulary
    # never to introduce at all. Both fail the same way on a card, so both are
    # gated here — a tier that nothing enforces is a style note, not a rule.
    for term, better in (*BANNED.items(), *PLAIN.items()):
        if re.search(rf"(?<![A-Za-z]){re.escape(term)}(?![A-Za-z])", text, re.IGNORECASE):
            raise AssertionError(
                f"{card.slug}: {term!r} reached the card — write {better!r} instead"
            )

    if "20 mm" not in text:
        raise AssertionError(f"{card.slug}: no 20 mm calibration tick on the back")
    return text


def gate_deck(texts: dict[str, str]) -> None:
    """Every algorithm the set claims to teach must be on some card, in the
    form that card prints it."""
    flat = re.sub(r"\s+", "", "".join(texts.values()))
    missing = [
        k
        for k, chunks in {**CHUNKS, **PLL_CHUNKS}.items()
        if not all(compact(seg) in flat for chunk in chunks for seg in chunk)
    ]
    missing += [
        k
        for k, chunks in BIGCUBE_CHUNKS.items()
        if not all(re.sub(r"\s+", "", seg) in flat for chunk in chunks for seg in chunk)
    ]
    if missing:
        raise AssertionError(f"algorithms missing from the rendered set: {sorted(set(missing))}")


def _sheet_jobs() -> list[tuple[str, Callable[[], str], JsonRow | None]]:
    """Every print sheet: (stem, a thunk for its Typst source, manifest row).

    `main` compiles this list and `manifest` publishes the third element, so a
    renamed sheet cannot leave the app pointing at a file the build never wrote
    — the failure `print.astro` used to be one hand-typed string away from.

    The source is a thunk, not a string: `manifest()` needs only the stems and
    metadata, and building every sheet's full Typst body — cut guides,
    calibration strips, all eight card boxes — to read six filenames rendered
    the whole imposition a second time on every build.
    """
    jobs: list[tuple[str, Callable[[], str], JsonRow | None]] = []
    for paper, (w, h) in SHEETS.items():
        jobs.append(
            (
                f"deck-{paper}-fold",
                functools.partial(_foldover, w, h, [c.index for c in DECK]),
                {"paper": paper, "mode": "fold", "flip": None},
            )
        )
        for flip in ("long", "short"):
            jobs.append(
                (
                    f"deck-{paper}-duplex-{flip}",
                    functools.partial(_duplex, w, h, flip),
                    {"paper": paper, "mode": "duplex", "flip": flip},
                )
            )
        for c in DECK:
            # Per-card reprints are reached through the card's own manifest row.
            jobs.append(
                (
                    f"card-{c.index}-{c.slug}-fold-{paper}",
                    functools.partial(_foldover, w, h, [c.index] * 4),
                    None,
                )
            )
    return jobs


def deck_sheets() -> list[JsonRow]:
    """The whole-deck print sheets, in build order."""
    return [{"file": f"{stem}.pdf", **meta} for stem, _, meta in _sheet_jobs() if meta]


def manifest() -> dict[str, list[JsonRow]]:
    """One table driving the app ladder and the print page: the ordered
    cards, plus every whole-deck sheet the build writes."""
    return {"cards": _card_rows(), "sheets": deck_sheets()}


def _card_rows() -> list[JsonRow]:
    return [
        {
            "index": c.index,
            "route": f"/c{c.index}",
            "slug": c.slug,
            "title": c.title,
            "num": c.num,
            "of": TIERS if c.num else None,
            "unlock": c.unlock,
            "master": c.master,
            "next": c.next_title,
            "next_slug": c.next.slug if c.next else None,
            "supersedes": c.supersedes,
            "superseded_by": c.superseded_by,
            "card_pdf": f"card-{c.index}-{c.slug}.pdf",
            "fold_pdf": {s: f"card-{c.index}-{c.slug}-fold-{s}.pdf" for s in SHEETS},
        }
        for c in DECK
    ]


def measure_faces() -> dict[str, float]:
    """Rendered content height of every card face, in mm. Diagnostic only —
    the build gate lives in the Typst source so a bad card cannot compile."""
    write_sources(strict=False)
    src = _OUT / "_measure.typ"
    lines = [
        '#import "card-body.typ": *',
        "#set page(width: 400mm, height: auto, margin: 4mm)",
    ]
    for c in DECK:
        for f in ("front", "back"):
            lines.append(
                f"#context [{c.slug}|{f}|"
                f"#calc.round(measure(block(width: {USABLE_W}mm, "
                f"style(body-{c.index}-{f}))).height.mm(), digits: 2)|MM\\ ]"
            )
    src.write_text("\n".join(lines))
    pdf = _OUT / "_measure.pdf"
    out = {}
    try:
        _compile(src, pdf)
        for line in pdf_text(pdf).splitlines():
            line = line.strip().replace(" ", "")
            if "|MM" not in line:
                continue
            slug, face, mm, _ = line.split("|")
            out[f"{slug} {face}"] = float(mm)
    finally:
        # `make cards` copies guide/build/cards/*.pdf into app/public/cards, so
        # a probe left behind by a failed measure ships as a printable. Clean
        # up and restore the strict sources even when the compile blew up.
        src.unlink(missing_ok=True)
        pdf.unlink(missing_ok=True)
        write_sources(strict=True)
    return out


def main() -> None:
    counts = build_print_svgs()
    write_sources()
    outputs, texts = [], {}

    cards = [
        (_OUT / f"card-{c.index}-{c.slug}.typ", _OUT / f"card-{c.index}-{c.slug}.pdf") for c in DECK
    ]
    sheets = []
    for stem, source, _ in _sheet_jobs():
        src = _OUT / f"{stem}.typ"
        src.write_text(source())
        sheets.append((src, _OUT / f"{stem}.pdf"))

    _compile_all(cards + sheets)

    for c, (_, pdf) in zip(DECK, cards, strict=True):
        texts[c.slug] = gate_card(c, pdf)
        outputs.append(pdf)
    gate_deck(texts)
    outputs.extend(pdf for _, pdf in sheets)

    payload = json.dumps(manifest(), indent=2) + "\n"
    (_OUT / "manifest.json").write_text(payload)
    # The app imports this at build time to render the frozen /c0../c3 routes,
    # so the ladder on the web is the deck table, never a second copy of it.
    CARDS_JSON.write_text(payload)
    print(f"card-style diagrams re-rendered: {sum(counts.values())} ({counts})")
    print(f"  {(_OUT / 'manifest.json').relative_to(_REPO)}")
    for o in outputs:
        print(f"  {o.relative_to(_REPO)}")


if __name__ == "__main__":
    main()

# ── Card bodies ───────────────────────────────────────────────────────


def _footer(card: Card, face: str) -> str:
    """Front footer carries the trigger legend; back carries the ladder."""
    if face == "front":
        legend = " ".join(
            f"#sw(C{f.upper()})~#mn[{prime(compact(t))}]~{label}#h(1.1mm)"
            for f, (t, label) in FAMILIES.items()
        )
        return f"#foot[{legend} gap = change grip]"

    lines = [esc(n) for n in card.notes]
    if card.unlock:
        tail = esc(card.unlock)
        if card.master:
            tail += f" #sym.square.stroked {esc(card.master)}"
        if card.next_title:
            tail += f" · NEXT: {esc(card.next_title)}"
        lines.append(tail)
    lines.append("#tick20()")
    return "#foot[" + " \\\n".join(lines) + "]"


def _section(sec: str | tuple[str, str]) -> str:
    if isinstance(sec, str):
        return f"#full([\n{sec}\n])"
    left, right = sec
    return f"#cols([\n{left}\n], [\n{right}\n])"


def _card_body(card: Card, face: str) -> str:
    sections = (card.front if face == "front" else card.back)()
    letter = "A" if face == "front" else "B"
    body = "\n".join(_section(s) for s in sections)
    # The content is NOT a fixed-height block: identity band, sections and
    # footer simply flow, and `fit()` measures the total against USABLE_H. The
    # column rule stops above the footer because `cols` draws it as a grid
    # stroke, which resolves against the taller column rather than the card.
    return f"""#let body-{card.index}-{face} = [
#ident([{card.ident}], [{letter}], [{esc(card.title)}], {card.filled}, {lstar_grey(card.tint_L)})
{body}
{_footer(card, face)}
]
#let card-{card.index}-{face} = box(width: {CARD_W}mm, height: {CARD_H}mm,
  inset: {MARGIN}mm)[
#style(fit("{card.slug} {face}", body-{card.index}-{face}))]
"""


def write_sources(strict: bool = True) -> Path:
    """Write the shared card body module and one per-card entry point.

    `strict=False` turns the overflow gate into a pass-through, so
    `measure_faces` can report every face's height instead of stopping at the
    first one that overruns.
    """
    _OUT.mkdir(parents=True, exist_ok=True)
    body = _OUT / "card-body.typ"
    body.write_text(
        _preamble(strict)
        + "\n"
        + "\n".join(_card_body(c, f) for c in DECK for f in ("front", "back"))
    )
    for c in DECK:
        (_OUT / f"card-{c.index}-{c.slug}.typ").write_text(
            '#import "card-body.typ": *\n'
            f"#set page(width: {CARD_W}mm, height: {CARD_H}mm, margin: 0pt)\n"
            f"#card-{c.index}-front\n#pagebreak()\n#card-{c.index}-back\n"
        )
    return body


# ── Imposition ────────────────────────────────────────────────────────

SHEETS = {"a4": (210.0, 297.0), "letter": (215.9, 279.4)}

# Back-sheet slot s lands behind front slot sigma[s].
SIGMA_LONG = [1, 0, 3, 2, 5, 4, 7, 6]  # (r,c) -> (r, 1-c); content upright
SIGMA_SHORT = [6, 7, 4, 5, 2, 3, 0, 1]  # (r,c) -> (3-r, c); + whole-page 180
RHO = [7 - s for s in range(8)]  # whole-page 180 rotation


def _slots(w: float, h: float, cols: int, rows: int) -> tuple[list[float], list[float]]:
    x0, y0 = (w - cols * CARD_W) / 2, (h - rows * CARD_H) / 2
    return (
        [x0 + i * CARD_W for i in range(cols)],
        [y0 + i * CARD_H for i in range(rows)],
    )


def _cut_guides(
    w: float, h: float, xs: list[float], ys: list[float], box: tuple[float, float, float, float]
) -> str:
    """Hairlines across the sheet plus solid ticks in the margins — one
    straight cut serves a whole column.

    `xs`/`ys` are *every* cut line, and `box` is (left, top, right, bottom) of
    the printed block, which is where the margin ticks anchor. The two are not
    the same list on the fold-over sheet: its panels are two cards tall, so
    the block spans four card heights while only two of those edges are cuts —
    the crease is folded, never cut.
    """
    bx0, by0, bx1, by1 = box
    parts = []
    for x in xs:
        parts.append(
            f"  #place(top + left, dx: {x}mm, dy: 0mm, "
            f"rect(width: 0.07mm, height: {h}mm, fill: luma(190)))"
        )
        for dy in (by0 - 3, by1):
            parts.append(
                f"  #place(top + left, dx: {x - 0.05}mm, dy: {dy}mm, "
                f"rect(width: 0.1mm, height: 3mm, fill: black))"
            )
    for y in ys:
        parts.append(
            f"  #place(top + left, dx: 0mm, dy: {y}mm, "
            f"rect(width: {w}mm, height: 0.07mm, fill: luma(190)))"
        )
        for dx in (bx0 - 3, bx1):
            parts.append(
                f"  #place(top + left, dx: {dx}mm, dy: {y - 0.05}mm, "
                f"rect(width: 3mm, height: 0.1mm, fill: black))"
            )
    return "\n".join(parts)


def _strip(x0: float, bw: float, dy: float, text: str) -> str:
    return (
        f"  #place(top + left, dx: {x0}mm, dy: {dy}mm, box(width: {bw}mm)[\n"
        f"    #text(size: 7pt)[{text}]\n"
        f"    #box(width: 80mm, height: 1.4mm)[\n"
        f"      #place(bottom + left, rect(width: 80mm, height: 0.4mm, fill: black))\n"
        f"      #place(bottom + left, rect(width: 0.3mm, height: 1.4mm, fill: black))\n"
        f"      #place(bottom + right, rect(width: 0.3mm, height: 1.4mm, fill: black))]\n"
        f"  ])"
    )


def check_row_duplication() -> None:
    """The theorem the whole duplex scheme rests on.

    `FRONT_SLOTS[2k] == FRONT_SLOTS[2k+1]` is what makes the long-edge back
    page need *no* transform and the short-edge back page need exactly one
    whole-page rotation. A future reorder that interleaves cards silently
    scrambles every duplex print with no visible symptom on a proof sheet.
    """
    f = FRONT_SLOTS
    assert len(f) == 8, f"the sheet holds 8 slots, deck lays out {len(f)}"
    assert all(f[2 * k] == f[2 * k + 1] for k in range(4)), f"front list is not row-duplicated: {f}"
    assert [f[SIGMA_LONG[s]] for s in range(8)] == f, "long-edge back page is not the identity"
    assert [f[SIGMA_SHORT[s]] for s in range(8)] == f[::-1], "short-edge back page is not reversed"
    assert SIGMA_SHORT == [RHO[SIGMA_LONG[s]] for s in range(8)], "sigma_short != rho . sigma_long"
    assert all(SIGMA_LONG[SIGMA_LONG[s]] == s for s in range(8)), "sigma_long is not an involution"
    assert all(SIGMA_SHORT[SIGMA_SHORT[s]] == s for s in range(8)), (
        "sigma_short is not an involution"
    )


def check_mirror(w: float, h: float) -> None:
    """Centred grids register under either flip. Never compare floats with
    `==`: 40.54 + 202.48 + 53.98 sums to 297.00000000000006."""
    xs, ys = _slots(w, h, 2, 4)
    assert abs(xs[0] + xs[1] + CARD_W - w) <= 0.01, xs
    for r in range(2):
        assert abs(ys[r] + ys[3 - r] + CARD_H - h) <= 0.01, ys


def _duplex(w: float, h: float, flip: str) -> str:
    """Two complete sets per sheet, 2 x 4, for the named flip only.

    Never one file claiming to work under either setting: a naive whole-page
    180 rotation maps (r,c) -> (r, 1-c), which degenerates into the long-edge
    column swap and pairs Card 1's front with Card 2's back. That is invisible
    on a sheet of identical cards, which is how it survived until now.
    """
    check_row_duplication()
    check_mirror(w, h)
    xs, ys = _slots(w, h, 2, 4)
    bw, bh = 2 * CARD_W, 4 * CARD_H
    guides = _cut_guides(
        w, h, xs + [xs[0] + bw], ys + [ys[0] + bh], (xs[0], ys[0], xs[0] + bw, ys[0] + bh)
    )
    note = (
        f"Print at 100% / Actual size — do NOT fit to page. Two-sided, flip on the "
        f"{flip.upper()} edge. The numeral on both faces is your check: cut ONE card first. "
        f"This bar must measure exactly 80 mm:"
    )
    strips = (
        _strip(xs[0], bw, ys[0] - 9, note)
        + "\n"
        + _strip(xs[0], bw, ys[0] + 4 * CARD_H + 4.5, note)
    )

    def face(which: str) -> str:
        cells = []
        for s in range(8):
            x, y = xs[s % 2], ys[s // 2]
            cells.append(
                f"  #place(top + left, dx: {x}mm, dy: {y}mm, card-{FRONT_SLOTS[s]}-{which})"
            )
        return "\n".join(cells)

    back = f"{guides}\n{strips}\n{face('back')}"
    if flip == "short":
        # Emitting the same slot order and rotating the page places the card
        # laid at slot k physically at rho[k] = 7-k, so physical slot s gets
        # F[7-s] = reverse(F) — exactly what sigma_short requires.
        back = (
            f"#rotate(180deg, origin: center + horizon, block(width: {w}mm, height: {h}mm)[\n"
            f"{back}\n])"
        )
    return f"""#import "card-body.typ": *
#set page(width: {w}mm, height: {h}mm, margin: 0pt)
#[
{guides}
{strips}
{face("front")}
]
#pagebreak()
#[
{back}
]
"""


_FOLD_NOTE = (
    "Print at 100% / Actual size, SINGLE-sided. Crease along the grey line, fold so both "
    "printed faces are outward, glue, then cut. This bar must measure exactly 80 mm:"
)


def _foldover(w: float, h: float, indices: list[int]) -> str:
    """One single-sided sheet: back rotated 180 above the front, sharing the
    fold edge. No duplexer, no registration error, no flip choice.

    Sheet furniture matters as much here as on the duplex sheets, because this
    is the file `/print` and `docs/printing.md` send everyone to first: both
    promise an 80 mm calibration bar and hairlines to cut on, and this sheet
    used to carry neither.

    Only the *outer* edge of each panel is a cut. Folding maps the back's top
    edge exactly onto the front's bottom edge, so one line serves both layers;
    the crease itself is folded, never cut, and stays a lone grey hairline.
    """
    panel_h = 2 * CARD_H
    bw, bh = 2 * CARD_W, 2 * panel_h
    x0, y0 = (w - bw) / 2, (h - bh) / 2
    cells = []
    for i, idx in enumerate(indices):
        r, c = divmod(i, 2)
        x, y = x0 + c * CARD_W, y0 + r * panel_h
        cells.append(f"  #place(top + left, dx: {x}mm, dy: {y}mm, rotate(180deg, card-{idx}-back))")
        cells.append(f"  #place(top + left, dx: {x}mm, dy: {y + CARD_H}mm, card-{idx}-front)")
        cells.append(
            f"  #place(top + left, dx: {x}mm, dy: {y + CARD_H - 0.05}mm, "
            f"rect(width: {CARD_W}mm, height: 0.1mm, fill: luma(150)))"
        )
    guides = _cut_guides(
        w,
        h,
        [x0, x0 + CARD_W, x0 + bw],
        [y0 + panel_h, y0 + bh],
        (x0, y0, x0 + bw, y0 + bh),
    )
    return f"""#import "card-body.typ": *
#set page(width: {w}mm, height: {h}mm, margin: 0pt)
{guides}
{_strip(x0, bw, y0 - 9, _FOLD_NOTE)}
{chr(10).join(cells)}
"""



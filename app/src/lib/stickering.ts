/**
 * Stickering masks for <twisty-player>, in the Cubepath colour scheme.
 *
 * cubing.js hard-codes its cube palette per axis (U white, F green, R red) and
 * has no colour-scheme API, so the only way to show yellow on top / red front /
 * green right is the whole-cube setup rotation `SETUP_ALG`. That rotation
 * silently inverts every built-in `experimental-stickering` value, because a
 * stickering mask binds to the CUBIE, not to the slot — the stock OLL mask
 * would land on the bottom layer. So the player passes
 * `experimental-stickering-mask-orbits` instead, built here.
 *
 * The table below is DERIVED from cubing.js by scripts/gen-stickering.mjs and
 * pinned by tests/algs.spec.ts. Never hand-edit the generated region.
 *
 * On top of the stock mask, `maskFor` narrows the highlight to the pieces the
 * case's own algorithm actually fixes: anything already solved in the case
 * state is dimmed, so an OLL row highlights the misoriented pieces rather than
 * claiming the whole last layer.
 *
 * `maskFor` takes an optional `StageContext` (ladder + stage, see lib/ladders).
 * With one, the base mask comes from Cubepath's own ladder and carries THREE
 * tiers — highlight what this step solves, dim what an earlier step solved,
 * grey what the method has not reached — instead of cubing.js's two. Without
 * one it uses BASE_MASKS exactly as before, so every existing caller is
 * unchanged: the third tier is opt-in, per call site.
 *
 * Two invariants live in `build()` rather than in the tables, because they must
 * hold for what reaches the ATTRIBUTE and not merely for what a helper returns:
 *
 *  - A CENTRE IS NEVER GREY. Grey means "the method has not reached this
 *    piece"; a centre is fixed by definition and is the frame every recognition
 *    cue is written against. cubing.js's own `F2L` scope greys the U centre
 *    (`CENTERS:I-----`), which is how all 41 F2L cases shipped with a grey
 *    yellow centre. The ladder builds the rule in; here it is enforced on the
 *    no-ladder path too.
 *  - NARROWING IS ASPECT-AWARE. A stage that settles orientation is narrowed by
 *    orientation alone, one that settles permutation by permutation alone.
 *    Testing both, regardless of the stage, highlighted a piece whose relevant
 *    aspect was already correct on 53 of the 81 orientation/permutation cases.
 */
